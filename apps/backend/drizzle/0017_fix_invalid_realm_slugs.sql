      AND  d.fetched_at > k.fetched_at;
    UPDATE character_wcl_snapshots d SET character_id = keep
    WHERE  d.character_id = rec.id
      AND  NOT EXISTS (
             SELECT 1 FROM character_wcl_snapshots k
