-- Repairs character rows persisted under realms Blizzard doesn't publish
-- ("tarrenmill", "chamberof-aspects", "гордунни") before #92 resolved realms at
-- the API boundary. See issue #95.
--
-- Unlike 0001, the target is not guessed from the realm's shape: it's looked
-- up in REALM_SLUGS (src/generated/realmSlugs.ts), copied into realm_slugs
-- below. Its keys are the realm with every separator stripped; stripping
-- ASCII punctuation here matches that for every key in the table without
-- depending on the database's locale.
--
-- For each row whose realm resolves to a different slug:
--   * no row exists at the correct slug → rename it in place;
--   * one does → merge into it: per unique slot keep the newer snapshot,
--     re-point search_events and alt links (dropping the link between the
--     two rows), then delete the bad row. Its leftovers go with the cascade.
-- Rows are processed one at a time, so two bad spellings of the same realm
-- ("chamberof-aspects", "chamberofaspects") collapse onto one row.
--
-- Realms REALM_SLUGS can't resolve are left alone, as are rosters.characters:
-- those are user-owned share payloads, editable only with the edit secret.

CREATE TEMP TABLE realm_slugs (region text, key text, slug text);
