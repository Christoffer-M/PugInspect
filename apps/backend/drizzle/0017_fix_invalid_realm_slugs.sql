    SELECT id INTO keep
    FROM   characters
    WHERE  region = rec.region AND realm = rec.slug AND name = rec.name;

    IF keep IS NULL THEN
      UPDATE characters SET realm = rec.slug WHERE id = rec.id;
      CONTINUE;
    END IF;

    -- One snapshot per character: keep whichever side fetched last.
    DELETE FROM character_rio_snapshots k USING character_rio_snapshots d
    WHERE  k.character_id = keep AND d.character_id = rec.id AND d.fetched_at > k.fetched_at;
    UPDATE character_rio_snapshots SET character_id = keep
    WHERE  character_id = rec.id
      AND  NOT EXISTS (SELECT 1 FROM character_rio_snapshots WHERE character_id = keep);

    DELETE FROM character_blizzard_snapshots k USING character_blizzard_snapshots d
    WHERE  k.character_id = keep AND d.character_id = rec.id AND d.fetched_at > k.fetched_at;
    UPDATE character_blizzard_snapshots SET character_id = keep
    WHERE  character_id = rec.id
      AND  NOT EXISTS (SELECT 1 FROM character_blizzard_snapshots WHERE character_id = keep);

    DELETE FROM character_equipment_snapshots k USING character_equipment_snapshots d
    WHERE  k.character_id = keep AND d.character_id = rec.id AND d.fetched_at > k.fetched_at;
    UPDATE character_equipment_snapshots SET character_id = keep
    WHERE  character_id = rec.id
      AND  NOT EXISTS (SELECT 1 FROM character_equipment_snapshots WHERE character_id = keep);

